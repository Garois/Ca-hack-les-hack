"""Log-likelihood ratio test: base model vs a locally quantized copy (fp8 e4m3), on endpoint responses.
Per token: llr = log p_base(x) - log p_quant(x). Tokens generated by the base model -> E[llr] > 0;
by the quantized model -> E[llr] < 0. Reports mean llr and a z-score per endpoint.

Usage: python llr.py MODEL_ID SCHEME DATA_NAME [DATA_NAME ...]
SCHEME: fp8_tensor | fp8_channel | int8_channel | int4_g128
"""
import pickle
import sys

import numpy as np
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

import common
from score import build


NF4 = [-1.0, -0.6961928009986877, -0.5250730514526367, -0.39491748809814453, -0.28444138169288635,
       -0.18477343022823334, -0.09105003625154495, 0.0, 0.07958029955625534, 0.16093020141124725,
       0.24611230194568634, 0.33791524171829224, 0.44070982933044434, 0.5626170039176941, 0.7229568362236023, 1.0]


def quantize_(model, scheme):
    with torch.no_grad():
        for name, mod in model.named_modules():
            if not isinstance(mod, torch.nn.Linear) or "lm_head" in name:
                continue
            w = mod.weight.data.float()
            if scheme == "fp8_tensor":
                s = w.abs().max() / 448.0
                q = (w / s).to(torch.float8_e4m3fn).float() * s
            elif scheme == "fp8_channel":
                s = w.abs().amax(1, keepdim=True) / 448.0
                q = (w / s).to(torch.float8_e4m3fn).float() * s
            elif scheme == "int8_channel":
                s = w.abs().amax(1, keepdim=True) / 127.0
                q = torch.round(w / s).clamp(-127, 127) * s
            elif scheme == "int4_g128":
                o, i = w.shape
                if i % 128:
                    continue
                g = w.reshape(o, i // 128, 128)
                mx, mn = g.amax(-1, keepdim=True), g.amin(-1, keepdim=True)
                s = (mx - mn).clamp(min=1e-8) / 15
                z = torch.round(-mn / s)
                q = ((torch.round(g / s + z).clamp(0, 15) - z) * s).reshape(o, i)
            elif scheme == "nf4_b64":
                cb = torch.tensor(NF4, device=w.device)
                flat = w.reshape(-1, 64)
                am = flat.abs().amax(1, keepdim=True).clamp(min=1e-12)
                idx = ((flat / am)[..., None] - cb).abs().argmin(-1)
                q = (cb[idx] * am).reshape(w.shape)
            elif scheme == "int8_tensor":
                s = w.abs().max() / 127.0
                q = torch.round(w / s).clamp(-127, 127) * s
            else:
                raise ValueError(scheme)
            mod.weight.data = q.to(mod.weight.dtype)


@torch.no_grad()
def token_logps(model, tok, rows):
    out = []
    for r in rows:
        ids_ctx = tok(build(tok, r["prompt"], None), add_special_tokens=False)["input_ids"]
        ids_resp = tok(r["response"], add_special_tokens=False)["input_ids"]
        if not ids_resp:
            out.append(np.zeros(0)); continue
        ids = torch.tensor([ids_ctx + ids_resp], device="cuda")
        logp = torch.log_softmax(model(ids).logits[0, len(ids_ctx) - 1:-1].float(), -1)
        out.append(logp.gather(1, ids[0, len(ids_ctx):, None])[:, 0].cpu().numpy())
    return out


if __name__ == "__main__":
    mid, scheme, datas = sys.argv[1], sys.argv[2], sys.argv[3:]
    keep = None
    if mid.startswith("fam:"):
        from fams import FAMILIES
        mid, keep = FAMILIES[mid[4:]]
    rows = [r for d in datas for r in common.load(d) if keep is None or r["endpoint"] in keep]
    tok = AutoTokenizer.from_pretrained(mid)
    model = AutoModelForCausalLM.from_pretrained(mid, dtype=torch.float32, device_map="cuda").eval()
    base = token_logps(model, tok, rows)
    quantize_(model, scheme)
    quant = token_logps(model, tok, rows)
    by = {}
    for r, a, b in zip(rows, base, quant):
        by.setdefault(r["endpoint"], []).append(a - b)
    tag = mid.split("/")[-1]
    with open(common.DATA / f"llr_{'+'.join(datas)}__{tag}__{scheme}.pkl", "wb") as f:
        pickle.dump({"rows": [{k: r[k] for k in ('endpoint', 'id', 'repeat')} for r in rows], "base": base, "quant": quant}, f)
    print(f"{tag} {scheme} on {datas}")
    for ep in sorted(by):
        d = np.concatenate(by[ep])
        # per-response sums are ~independent: z from response-level totals
        sums = np.array([x.sum() for x in by[ep]])
        z = sums.sum() / (np.sqrt((sums ** 2).sum()) + 1e-9)
        print(f"  {ep}: mean_llr={d.mean():+.5f}  sum={d.sum():+8.2f}  z={z:+.2f}  ntok={len(d)}")
